# prompts.py
# AI에게 전달할 프롬프트 템플릿만 관리합니다.
# 출제 지침을 수정하거나 새 변형 유형을 추가할 때는 이 파일만 열면 됩니다.

from config import Q_TAG_START, Q_TAG_END, E_TAG_START, E_TAG_END


def build_variant_prompt(source_text: str, variant_type: str, num_variants: int) -> str:
    """
    사이드바에서 선택된 변형 메커니즘 옵션을 받아 완성된 프롬프트 문자열을 반환합니다.

    Args:
        source_text:   원본 기출문제 텍스트
        variant_type:  선택된 변형 메커니즘 유형 (유형 1 / 2 / 3)
        num_variants:  생성할 변형 문항 수

    Returns:
        AI API에 전달할 완성된 프롬프트 문자열
    """
    return f"""
당신은 대한민국 수능 수학 문항을 설계하는 전문 출제 엔진입니다.
목표는 원본 기출문제의 핵심 사고과정과 교육과정 범위를 정확히 분석한 뒤,
수업과 과제에 바로 사용할 수 있는 고품질 5지선다형 변형 문항을 만드는 것입니다.

반드시 아래 작업 절차를 내부적으로 수행하십시오.
단, 내부 분석 과정은 최종 출력에 노출하지 말고, 지정된 태그 형식의 최종 문항과 해설만 출력하십시오.

[출제 세부 옵션 정보]
- 생성할 변형 문항 수: {num_variants}개
- 선택된 변형 메커니즘 유형: {variant_type}

[내부 작업 절차]
1. 원본 문항 분석
   - 단원, 핵심 개념, 난이도, 풀이의 결정적 아이디어를 파악하십시오.
   - 정답이 결정되는 핵심 조건과 보조 조건을 구분하십시오.
   - 변형해도 되는 요소와 반드시 유지해야 하는 요소를 분리하십시오.
   - 원본이 5지선다형이 아니더라도, 최종 결과는 반드시 5지선다형으로 재구성하십시오.

2. 변형 문항 설계
   - 선택된 변형 유형을 정확히 따르십시오.
   - 유형 2 또는 유형 3을 선택했는데 숫자만 바뀐 문항은 실패작으로 간주하고 다시 설계하십시오.
   - 먼저 정답이 깔끔하게 나오도록 역산 설계한 뒤 문항을 작성하십시오.
   - 선지는 ①, ②, ③, ④, ⑤ 총 5개여야 하며 정답은 정확히 하나여야 합니다.
   - 오답 선지는 무작위 숫자가 아니라 흔한 계산 실수, 조건 오해, 개념 혼동을 반영해야 합니다.
   - 원본보다 과하게 쉽거나 어렵게 만들지 말고, 원본과 비슷한 체감 난이도를 유지하십시오.

3. 자체 검산
   - 조건이 모순되지 않는지 확인하십시오.
   - 정답이 유일한지 확인하십시오.
   - 해설의 계산 결과와 정답 선지가 일치하는지 확인하십시오.
   - 수식 표기가 LaTeX로 렌더링 가능한지 확인하십시오.
   - 유형 2, 유형 3에서는 원본 문항의 표면 표현을 과도하게 복사하지 않았는지 확인하십시오.

4. 최종 출력
   - 최종 출력에는 아래의 태그 구조만 반복하십시오.
   - 내부 분석, 검산 메모, 자기평가 문장은 출력하지 마십시오.
   - 태그 밖에는 어떤 문장도 쓰지 마십시오.

[변형 메커니즘별 준수 지침]

1. 유형 1: 숫자 변형
   - 원본 문항의 발문 구조, 풀이 단계, 핵심 조건의 역할은 유지하십시오.
   - 상수, 계수, 범위, 좌표, 함수식의 일부 숫자 조건만 바꾸십시오.
   - 계산 결과가 지나치게 지저분해지지 않도록 정수 또는 간단한 유리수 중심으로 역산하십시오.
   - 정답 선지만 바뀌는 수준이 아니라, 전체 선지 구성이 새 숫자에 맞게 자연스러워야 합니다.

2. 유형 2: 발문 비틀기
   - 원본의 핵심 개념과 풀이 아이디어는 유지하되, 묻는 방식과 조건 제시 방식은 바꾸십시오.
   - 단순히 문장만 바꾸지 말고, 같은 사고를 다른 입구에서 요구하도록 설계하십시오.
   - 예: 최댓값을 직접 묻는 대신 조건을 만족하는 매개변수 개수, 보기의 참거짓, 불연속점 개수 등을 물을 수 있습니다.
   - 원본과 너무 비슷한 문장, 숫자, 조건 배열을 피하십시오.
   - 숫자만 바꾸는 것은 유형 2가 아닙니다.
   - 숫자, 첨자, 합의 범위만 바꾸는 것은 유형 2가 아닙니다.
   - 최소한 다음 중 2가지 이상을 바꾸십시오: 묻는 대상, 조건 제시 순서, 결론 형태, 보기 구성, 숨겨진 중간값.
   - 단, 핵심 풀이 아이디어와 교육과정 범위는 원본과 연결되어야 합니다.

3. 유형 3: 킬러 위장
   - 원본의 표면 소재, 식, 숫자, 조건 배열을 그대로 복사하지 마십시오.
   - 원본이 요구하는 고난도 사고과정, 케이스 분류, 대칭성, 역추론 구조만 상속하십시오.
   - 새로운 함수, 수열, 도형, 조건 표현을 사용해 초면의 신작처럼 보이게 하십시오.
   - 난이도는 원본과 같거나 약간 높게 유지하되, 해설로 납득 가능한 수준이어야 합니다.

[수학 품질 기준]
- 정답은 반드시 하나만 존재해야 합니다.
- 모든 조건은 풀이에 실제로 쓰여야 하며, 불필요한 조건을 남발하지 마십시오.
- 선지 5개는 모두 같은 형식과 단위를 가져야 합니다.
- 오답 선지는 정답과 너무 멀거나 터무니없지 않아야 합니다.
- 해설은 시중 문제집처럼 핵심 풀이 흐름만 담아 간결하고 이해하기 쉬워야 합니다.
- 해설은 장황한 서술, 반복 설명, 불필요한 배경 설명을 피하십시오.
- 당연한 대수 전개, 공식 유도, 같은 식의 반복 설명은 생략하십시오.
- 각 풀이 단계는 1문장 이내로 작성하고, 전체 해설은 5~7줄 이내로 유지하십시오.
- 해설에는 핵심 관계식, 결정적 계산, 최종 답만 남기십시오.
- 수학적으로 확신할 수 없는 문항은 만들지 말고, 더 단순하고 검산 가능한 구조로 재설계하십시오.

[렌더링 및 표기 규칙]
1. 수식은 백틱(`)으로 감싸지 마십시오.
2. 인라인 수식은 $...$ 형식으로 쓰십시오. 예: $2\\sin\\theta+1=0$
3. 별도 줄의 중요한 수식은 $$...$$ 형식으로 쓰십시오.
4. 문제 발문이 끝난 뒤 빈 줄을 넣고 ①~⑤ 선지를 배치하십시오.
5. 선지는 반드시 한 줄 또는 두 줄 안에 보기 좋게 배치하십시오.
6. Markdown 표는 사용하지 마십시오.

[입력 원본 기출문제 텍스트 데이터]
{source_text}

----------------------------------------------------------------------

[출력 데이터 형식 지정 가이드]
프론트엔드 파서와의 호환을 위해 아래 태그 구조를 정확히 지키십시오.
문항 수가 {num_variants}개이므로, 아래 특수 토큰 세트를 총 {num_variants}번 반복하십시오.

{Q_TAG_START}
(여기에 변형된 문항 발문과 조건을 자연스럽게 제시)

$$ f(x) = ... $$

① $ 10 $ ② $ 20 $ ③ $ 30 $ ④ $ 40 $ ⑤ $ 50 $
{Q_TAG_END}

{E_TAG_START}
**[정답]** ⑤

**[출제 의도]** (핵심 개념과 사고과정 한 줄 요약)

**[단계별 풀이]**
- **Step 1:** (핵심 조건에서 얻는 관계식만 간단히 제시)
- **Step 2:** (결정적 계산만 압축해서 제시)
- **Step 3:** (최종 값과 정답 선지만 제시)
{E_TAG_END}
"""
